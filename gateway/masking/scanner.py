"""Response scanner to detect and handle sensitive data leaks in model completions."""

from dataclasses import dataclass
from typing import List, Optional

from gateway.detectors.base import DetectionSpan
from gateway.detectors.engine import DetectorEngine


@dataclass
class ResponseScanResult:
    has_violations: bool
    detections: List[DetectionSpan]
    sanitized_text: str


class ResponseScanner:
    """Scans LLM completions to prevent exfiltration or output leakage of secrets and PII."""

    def __init__(self, detector_engine: Optional[DetectorEngine] = None):
        self.engine = detector_engine or DetectorEngine()

    def scan_response(self, response_text: str, mask_violations: bool = True) -> ResponseScanResult:
        """Scan response text for sensitive information.

        Args:
            response_text: Raw output string generated by LLM provider.
            mask_violations: If True, replaces detected leaks with REDACTED placeholders.

        Returns:
            ResponseScanResult with violation status, detected spans, and sanitized text.
        """
        detections = self.engine.detect_all(response_text)
        if not detections:
            return ResponseScanResult(
                has_violations=False, detections=[], sanitized_text=response_text
            )

        if not mask_violations:
            return ResponseScanResult(
                has_violations=True, detections=detections, sanitized_text=response_text
            )

        # Sanitize detections from right to left
        sanitized_chars = list(response_text)
        for span in sorted(detections, key=lambda s: s.start, reverse=True):
            placeholder = f"<GW_REDACTED_{span.entity_type.value}>"
            sanitized_chars[span.start : span.end] = list(placeholder)

        return ResponseScanResult(
            has_violations=True, detections=detections, sanitized_text="".join(sanitized_chars)
        )
